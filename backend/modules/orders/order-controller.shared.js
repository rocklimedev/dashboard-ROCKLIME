const fetchCommentsWithUsers = async (resourceId, resourceType, pageNum, limitNum) => {
  const comments = await Comment.find({ resourceId, resourceType })
    .sort({ createdAt: -1 })
    .skip((pageNum - 1) * limitNum)
    .limit(limitNum)
    .lean();

  const commentsWithUsers = await Promise.all(
    comments.map(async (comment) => {
      const user = await User.findOne({
        where: { userId: String(comment.userId) },
        attributes: ['userId', 'username', 'name'],
      });
      return {
        ...comment,
        user: user ? user.toJSON() : null,
      };
    }),
  );

  const totalCount = await Comment.countDocuments({ resourceId, resourceType });

  return { comments: commentsWithUsers, totalCount };
};

/**
 * Compute totals (GST, extra discount, final amount, amountPaid validation)
 * @returns {{gstValue, extraDiscountValue, subTotal, finalTotal}}
 */
function computeTotals({
  products = [],
  shipping = 0,
  gst = 0,
  extraDiscount = 0,
  extraDiscountType = 'fixed',
}) {
  // Same maths as quotations (lib/quotationMath): discounts → taxable value →
  // GST on the taxable value → round to the rupee at the very end.
  const t = quotationTotals({
    items: products.map((p) => ({
      price:
        p.total != null ? Number(p.total) || 0 : (Number(p.price) || 0) * (Number(p.quantity) || 1),
      quantity: 1,
    })),
    shipping,
    gstRate: gst,
    extraDiscount,
    extraDiscountType,
  });
  return {
    subTotal: t.goodsValue,
    totalWithShipping: r2(t.goodsValue + t.freight),
    gstValue: t.gstAmount,
    extraDiscountValue: t.extraDiscountAmount,
    taxableValue: t.taxableValue,
    roundOff: t.roundOff,
    finalAmount: t.grandTotal,
  };
}

